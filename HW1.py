# – замінити кожне 4-те значення на ‘X’


def replace_fourth():
    l_copy[3::4] = "X" * len(l_copy[3::4])
    print(l_copy)


# 2. вивести на екран пустий квадрат з “\*”, сторона якого вказана як аргумент функції


def draw_square(size):
    for i in range(size):
        if i == 0 or i == size - 1:
            print("*" * size)
        else:
            print("*" + " " * (size - 2) + "*")


