def multiplication_table():
    i = 1
    while i <= 10:
        j = 1
        while j <= 10:
            # print(" " if i * j // 10 else "  ", end="")
            # print(i * j, end="")
            print(f"{i * j:4}", end="")
            j += 1
        print()
        i += 1


